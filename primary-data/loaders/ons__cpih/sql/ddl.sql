-- Таблица первичных данных: ONS CPIH (Consumer Prices Index including owner
-- occupiers' housing costs), месячные наблюдения, несколько серий датасета MM23
-- в одной таблице — серия различается колонкой cdid.
--
-- Значения как в источнике, без очистки, пересчёта и агрегации. Единственная
-- производная колонка — period (месяц из текстового date, чтобы было чем
-- сортировать и джойнить); значения наблюдений не трогаются.
--
-- Описание каждой серии на сайте ONS открывается по её cdid:
--   https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries/<cdid в нижнем регистре>/mm23
-- Методика и статус статистики — Consumer price inflation QMI:
--   https://www.ons.gov.uk/economy/inflationandpriceindices/methodologies/consumerpriceinflationincludesall3indicescpihcpiandrpiqmi
-- Бюллетень релиза — Consumer price inflation, UK:
--   https://www.ons.gov.uk/economy/inflationandpriceindices/bulletins/consumerpriceinflation/latest

create table if not exists "primary".ons__cpih (
    cdid         text        not null,
    title        text,
    unit         text,
    key_note     text,
    period       date        not null,
    date         text,
    year         integer,
    month        text,
    value        numeric,
    release_date timestamptz,
    update_date  timestamptz,
    primary key (cdid, period)
);

comment on table "primary".ons__cpih is
    'ONS CPIH, датасет MM23, месячные наблюдения. Показатель общенациональный '
    '(Великобритания), разбивки по районам нет — в проекте нужен как дефлятор: окно '
    'данных идёт с 1995 года, и без перевода цен в реальные модель выучит инфляцию. '
    'Серии: L522 — индекс всех товаров и услуг, L55O — его годовой темп прироста, '
    'CRQO — индекс без расходов собственников на жильё (OOH), L5PG — индекс дивизиона 04 '
    '(жильё, вода, электричество, газ, топливо), L55S — его годовой темп прироста. '
    'Разные серии начинаются в разные месяцы: индексы с 1988-01, годовые темпы '
    'прироста — с 1989-01 (первые 12 месяцев не определены по построению), так что '
    'сопоставлять серии между собой нужно внешним джойном, не внутренним. '
    'Официальная серия CPIH ведётся с 2013 года, история до этого достроена назад '
    'ретроспективно; статус accredited official statistics был приостановлен в 2014 '
    'из-за методики оценки OOH и возвращён 31 июля 2017. '
    'Источник: https://www.ons.gov.uk/economy/inflationandpriceindices/datasets/consumerpriceindices '
    'Владелец ONS, лицензия OGL v3.0.';

