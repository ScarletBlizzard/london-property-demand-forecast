comment on column "primary".ons__cpih.key_note is
    'Пояснение к единицам от ONS. У L522 — "Index, 2015 = 100", то есть база индекса: '
    'средний уровень цен 2015 года принят за 100. У L55O — "Change over 12 months". '
    'У CRQO, L5PG, L55S пусто — базу и смысл брать из title. ONS периодически '
    'перебазирует индексы (текущая база 2015=100, до неё была 2005=100): при '
    'перебазировании пересчитывается вся история, поэтому таблица всегда перезаливается '
    'целиком, а не досылается. Дублируется внутри серии';
